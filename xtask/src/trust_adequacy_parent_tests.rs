//! Parent controls for every generator position (generated-sources §5, M3.6.9.6.2.2).

use super::tests::{admit, manifest, refused, two_roots, written, Fixture, ROOTS};
use crate::json::Json;

const TABLE: &str = "crates/b/src/table.rs";

fn declaration(generators: &[&str]) -> (&'static str, String) {
    let names = generators
        .iter()
        .map(|p| format!("\"{p}\""))
        .collect::<Vec<_>>()
        .join(" ");
    (
        "trust/roots.eadl",
        format!(
            "{ROOTS}(defgenerated \"{TABLE}\" (generator {names}) (command \"generate\") (reason \"a table\"))\n"
        ),
    )
}

fn fixture(name: &str, files: &[(&str, String)]) -> Fixture {
    let mut all = vec![(TABLE, "pub const T: u32 = 7;\n".to_owned())];
    all.extend_from_slice(files);
    two_roots(
        name,
        "fn main() {}\n",
        "mod table; pub fn value() -> u32 { table::T }\n",
        &all,
    )
}

fn exact_refusals(actual: Vec<String>, expected: Vec<String>) {
    let mut actual = actual;
    let mut expected = expected;
    actual.sort();
    expected.sort();
    assert_eq!(actual, expected);
}

#[test]
fn every_script_position_is_judged_against_the_reading_role() {
    let neutral = ["scripts/first.sh", "scripts/middle.sh", "scripts/last.sh"];
    let foreign = [
        "crates/a/first.sh",
        "crates/a/middle.sh",
        "crates/a/last.sh",
    ];
    let own = [
        "crates/b/first.sh",
        "crates/b/middle.sh",
        "crates/b/last.sh",
    ];
    let mut files: Vec<_> = neutral
        .iter()
        .chain(&foreign)
        .chain(&own)
        .map(|p| (*p, "echo generate\n".to_owned()))
        .collect();
    files.push(declaration(&neutral));
    let f = fixture("adequacy-script-positions", &files);
    written(f.run_into("neutral"));
    f.commit(&[declaration(&own)]);
    written(f.run_into("own"));
    f.commit(&[declaration(&foreign)]);
    exact_refusals(
        refused(f.run_into("foreign")),
        foreign
            .iter()
            .map(|p| format!(
                "trust-shared-program: `chk` reads `{TABLE}`, generated by `{p}`, which lies in `crates/a`, a role package of the generator"
            ))
            .collect(),
    );
}

#[test]
fn every_program_target_position_is_refused_before_a_foreign_role_build() {
    let generators = [
        "crates/a/src/first.rs",
        "crates/a/src/middle.rs",
        "crates/a/src/last.rs",
    ];
    let targets = "[[bin]]\nname = \"first\"\npath = \"src/first.rs\"\n\
                   [[bin]]\nname = \"middle\"\npath = \"src/middle.rs\"\n\
                   [[bin]]\nname = \"last\"\npath = \"src/last.rs\"\n";
    let mut files = vec![
        declaration(&generators),
        ("crates/a/Cargo.toml", manifest("a", targets)),
    ];
    // Deliberately uncompilable: all targets must be refused before anything of them runs.
    files.extend(
        generators
            .iter()
            .map(|p| (*p, "fn main() { missing(); }\n".to_owned())),
    );
    let f = fixture("adequacy-target-role-positions", &files);
    exact_refusals(
        refused(f.run()),
        generators
            .iter()
            .zip(["first", "middle", "last"])
            .map(|(p, name)| format!(
                "trust-shared-program: `chk` reads `{TABLE}`, generated by `{p}`, the crate root of the bin `{name}` of `crates/a`, whose build compiles `crates/a`, a role package of the generator — not built"
            ))
            .collect(),
    );
    assert!(!f.base.join("out/target-generators").exists());
}

#[test]
fn every_unowned_rust_generator_position_has_its_own_refusal() {
    let generators = ["scripts/first.rs", "scripts/middle.rs", "scripts/last.rs"];
    let mut files = vec![declaration(&generators)];
    files.extend(generators.iter().map(|p| (*p, "fn main() {}\n".to_owned())));
    let f = fixture("adequacy-lone-rust-positions", &files);
    exact_refusals(
        refused(f.run()),
        generators
            .iter()
            .map(|p| format!(
                "trust-undeclared-input: trust/roots.eadl: `(defgenerated \"{TABLE}\" …)`'s generator `{p}` is a `.rs` file that is no program target's crate root — a generator file is a script or a program target's crate root, whose build the instrument computes"
            ))
            .collect(),
    );
}

#[test]
fn every_allowed_target_position_is_built_and_its_sites_are_judged() {
    let generators = [
        "crates/u/src/first.rs",
        "crates/u/src/middle.rs",
        "crates/u/src/last.rs",
    ];
    let targets = "[[bin]]\nname = \"first\"\npath = \"src/first.rs\"\n\
                   [[bin]]\nname = \"middle\"\npath = \"src/middle.rs\"\n\
                   [[bin]]\nname = \"last\"\npath = \"src/last.rs\"\n";
    let site = "#[no_mangle]\npub extern \"C\" fn generated_value() {}";
    let mut files = vec![
        declaration(&generators),
        ("crates/u/Cargo.toml", manifest("u", targets)),
    ];
    files.extend(
        generators
            .iter()
            .map(|p| (*p, format!("{site}\nfn main() {{}}\n"))),
    );
    let f = fixture("adequacy-target-build-positions", &files);
    exact_refusals(
        refused(f.run_into("unadmitted")),
        generators
            .iter()
            .map(|p| format!(
                "trust-undeclared-input: `{p}:1`: `no_mangle`, refused by the catalog's rules, and no admission names it (site sha256 5571563e034718b14aead1d7cf6df1755610ecf493abd76aa06fe43951f5a934)"
            ))
            .collect(),
    );
    for name in ["first", "middle", "last"] {
        assert!(f
            .base
            .join(format!("unadmitted/target-generators/crates-u-bin-{name}"))
            .exists());
    }
    let (path, mut roots) = declaration(&generators);
    for generator in generators {
        roots.push_str(&admit(generator, "no_mangle", site));
    }
    f.commit(&[(path, roots)]);
    let inventory = written(f.run_into("admitted"));
    assert_eq!(
        inventory.get("refused-sites").and_then(Json::as_str),
        Some("3")
    );
    assert!(inventory
        .get("admissions-unused")
        .expect("the unused-admission list")
        .elements()
        .is_empty());
}
