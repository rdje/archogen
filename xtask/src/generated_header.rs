    fn document(path: &str) -> String {
        std::fs::read_to_string(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("..")
                .join(path),
        )
        .unwrap_or_else(|e| panic!("{path}: {e}"))
    }

    /// A machine-read block of a document: the lines after `<!-- machine-read: NAME -->` up to the first blank one.
    fn block(path: &str, name: &str) -> Vec<String> {
        document(path)
            .split(&format!("<!-- machine-read: {name} -->"))
            .nth(1)
            .unwrap_or_else(|| panic!("{path}'s machine-read `{name}`"))
            .lines()
            .skip(1)
            .take_while(|l| !l.trim().is_empty())
            .map(str::to_owned)
            .collect()
    }

    fn record_block(name: &str) -> Vec<String> {
        block(DOCUMENTS[0], name)
    }

    #[test]
    fn the_record_s_markers_are_the_code_s() {
        let mut code: Vec<String> = super::MARKERS.iter().map(|m| (*m).to_owned()).collect();
        code.sort();
        for doc in DOCUMENTS {
            let mut listed: Vec<String> = block(doc, "markers")
                .join(" ")
                .split('`')
                .skip(1)
                .step_by(2)
                .map(str::to_owned)
                .collect();
            listed.sort();
            assert_eq!(
                listed, code,
                "{doc}'s markers and generated_header::MARKERS"
            );
        }
    }

    #[test]
    fn every_rule_the_record_states_has_a_catalogued_mutation_and_every_mutation_a_rule() {
        // The record's §3 maps each rule of the recogniser to the `gh-…` mutation that breaks it; each must be in
        // `xtask/mutations.txt`, aimed at this file and expected killed — `cargo xtask mutate` runs it — and every
        // such entry must be one the record lists.
        let rows = record_block("recogniser-mutations");
        let listed: std::collections::BTreeSet<String> = rows
            .iter()
            .skip(2)
            .filter_map(|r| r.split('|').nth(2))
            .map(|c| c.trim().trim_matches('`').to_owned())
            .collect();
        assert!(!listed.is_empty(), "the record lists its rules' mutations");
        let catalog = std::fs::read_to_string(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("mutations.txt"),
        )
        .expect("the catalog");
        let mut aimed = std::collections::BTreeSet::new();
        for entry in catalog.split("\nmutation ").skip(1) {
            let name = entry.lines().next().unwrap_or("").trim().to_owned();
            if entry
                .lines()
                .any(|l| l == "file xtask/src/generated_header.rs")
            {
                assert!(
                    entry.lines().any(|l| l == "expect killed"),
                    "{name} is expected killed"
                );
                aimed.insert(name);
            }
        }
        assert_eq!(
            listed, aimed,
            "the record's rule-to-mutation table and the catalogue's entries for this file"
        );
    }

