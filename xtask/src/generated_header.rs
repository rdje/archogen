//! The generated-source marker (leaf `M3.6.6.1`; `docs/specs/trust/decision_trust-generated-sources.md` §3): the rule
//! that says whether a file declares, in its header, that a generator wrote it — stated as code, with its corpus,
//! because two rounds of prose left cases two readers would decide differently.
//!
//! **The header** is the text of the comments that come before the file's first character that is neither whitespace
//! nor inside a comment. Comment syntax is the file's language's, by its extension or name ([`syntax`]); a file with
//! none has an empty header and is never marked; a file's bytes are read as UTF-8, an invalid sequence as U+FFFD; a file with no
//! extension whose first line is a `#!` is read with `#` comments. A `#!` first line is a comment where `#` is; in Rust
//! it is one when rustc reads it as a shebang ([`rust_shebang`], held to the pinned rustc by a test), and it then ends
//! at a line feed alone. Block comments nest in Rust, Kotlin, Swift and Scala, and in no other language here; an unclosed block
//! runs to the end of the file. Any other line ends at `\n` or `\r`. An XML declaration (`<?xml … ?>`) may come before the
//! comments of an `<!-- -->` file. **Marked** means the header holds one of [`MARKERS`], in any case.
//!
//! The record states these rules as the rows of a table, each broken by a catalogued mutation (`xtask/mutations.txt`)
//! the corpus or the fixture kills; `scripts/mutation_sweep.sh` holds the rest of its functions, every mutation its
//! operators make killed, timed out or not compiling, or listed, with its reason, in `xtask/generated_header.equivalents`.

/// The phrases that mark a header, compared without regard to case.
pub const MARKERS: &[&str] = &[
    "@generated",
    "do not edit",
    "automatically generated",
    "auto-generated",
    "autogenerated",
    "generated by",
];

/// A language's comment syntax, as far as the header needs it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Syntax {
    /// `//` lines and `/* */` blocks; Rust's, Kotlin's, Swift's and Scala's nest.
    Slash {
        /// Whether a `/*` inside a block opens another.
        nests: bool,
    },
    /// `/* */` blocks alone, not nesting (CSS).
    Block,
    /// `#` lines.
    Hash,
    /// `;` lines.
    Semicolon,
    /// `--` lines.
    Dash,
    /// `<!-- -->` blocks.
    Angle,
    /// No comment syntax: never marked.
    None,
}

/// The extensions and the file names each syntax is read for: the whole of the recogniser's reach. §3 of the
/// generated-sources record and the book's trust chapter hold the same table, machine-read, and a test holds each
/// equal to this one.
pub const TABLE: &[(Syntax, &[&str], &[&str])] = &[
    (
        Syntax::Slash { nests: true },
        &["rs", "kt", "swift", "scala"],
        &[],
    ),
    (
        Syntax::Slash { nests: false },
        &[
            "c", "h", "cc", "cpp", "cxx", "hh", "hpp", "hxx", "js", "ts", "go", "java", "proto",
        ],
        &[],
    ),
    (Syntax::Block, &["css"], &[]),
    (
        Syntax::Hash,
        &[
            "sh", "bash", "zsh", "py", "rb", "pl", "r", "toml", "yml", "yaml", "cmake", "mk",
            "env", "conf",
        ],
        &[
            "Makefile",
            "makefile",
            "GNUmakefile",
            "Dockerfile",
            "CMakeLists.txt",
            ".env",
        ],
    ),
    (
        Syntax::Semicolon,
        &["eadl", "el", "lisp", "clj", "s", "asm", "ini"],
        &[],
    ),
    (
        Syntax::Dash,
        &["sql", "lua", "hs", "ada", "adb", "ads", "vhd", "vhdl"],
        &[],
    ),
    (Syntax::Angle, &["md", "html", "htm", "xml", "svg"], &[]),
];

/// A file name's extension: what follows its last `.`, when a `.` comes after its first character and something follows
/// it — so a dotfile such as `.env` has none and is read by its name, and `foo.` has none either.
fn extension(name: &str) -> Option<String> {
    let first = name.chars().next()?;
    let rest = &name[first.len_utf8()..];
    rest.rsplit_once('.')
        .map(|(_, e)| e.to_ascii_lowercase())
        .filter(|e| !e.is_empty())
}

/// The comment syntax of the file at `path`: by its exact name first, then by its extension in any case.
#[must_use]
pub fn syntax(path: &str) -> Syntax {
    let name = path.rsplit('/').next().unwrap_or(path);
    let ext = extension(name).unwrap_or_default();
    TABLE
        .iter()
        .find(|(_, _, names)| names.contains(&name))
        .or_else(|| {
            TABLE
                .iter()
                .find(|(_, exts, _)| !ext.is_empty() && exts.contains(&ext.as_str()))
        })
        .map_or(Syntax::None, |(syn, _, _)| *syn)
}

/// Rust's `Pattern_White_Space`, which rustc's lexer skips between `#!` and `[`.
fn pattern_white_space(c: char) -> bool {
    matches!(
        c,
        '\u{9}'..='\u{d}' | ' ' | '\u{85}' | '\u{200e}' | '\u{200f}' | '\u{2028}' | '\u{2029}'
    )
}

/// Whether rustc reads a Rust file opening `#!` as a shebang: unless what follows the `#!` is `[`, with
/// `Pattern_White_Space` and plain comments skipped — block comments nesting, a line comment ending at a line feed, and
/// `////`, `/**/` and `/***` plain — while a doc comment (`///`, `//!`, `/**`, `/*!`) ends the look-ahead. The
/// test `the_shebang_rule_is_rustc_s` compiles each case with the pinned rustc and holds this to it.
#[must_use]
pub fn rust_shebang(s: &[char]) -> bool {
    let at = |i: usize, pat: &str| -> bool {
        pat.chars()
            .enumerate()
            .all(|(k, c)| s.get(i + k) == Some(&c))
    };
    if !at(0, "#!") {
        return false;
    }
    let mut j = 2;
    loop {
        while j < s.len() && pattern_white_space(s[j]) {
            j += 1;
        }
        let doc = (at(j, "///") && !at(j, "////"))
            || at(j, "//!")
            || (at(j, "/**") && !at(j, "/**/") && !at(j, "/***"))
            || at(j, "/*!");
        if doc {
            return true;
        }
        if at(j, "//") {
            while j < s.len() && s[j] != '\n' {
                j += 1;
            }
        } else if at(j, "/*") {
            j += 2;
            let mut depth = 1usize;
            while j < s.len() && depth > 0 {
                if at(j, "/*") {
                    depth += 1;
                    j += 2;
                } else if at(j, "*/") {
                    depth -= 1;
                    j += 2;
                } else {
                    j += 1;
                }
            }
        } else {
            return s.get(j) != Some(&'[');
        }
    }
}

/// The header's comment text, empty when the file has no comment syntax. Its bytes are read as UTF-8, an invalid
/// sequence as U+FFFD, so one bad byte after a clean header does not hide it.
fn header(path: &str, bytes: &[u8]) -> String {
    let name = path.rsplit('/').next().unwrap_or(path);
    let decoded = String::from_utf8_lossy(bytes);
    let text = decoded.strip_prefix('\u{feff}').unwrap_or(&decoded);
    let syn = match syntax(path) {
        Syntax::None if extension(name).is_none() && text.starts_with("#!") => Syntax::Hash,
        other => other,
    };
    let s: Vec<char> = text.chars().collect();
    let (mut i, mut out) = (0usize, String::new());
    let at = |i: usize, pat: &str| -> bool {
        pat.chars()
            .enumerate()
            .all(|(k, c)| s.get(i + k) == Some(&c))
    };
    let line = |i: &mut usize, out: &mut String| {
        while *i < s.len() && s[*i] != '\n' && s[*i] != '\r' {
            out.push(s[*i]);
            *i += 1;
        }
        out.push('\n');
    };
    // A `#!` first line: in Rust a comment when `rust_shebang` says rustc reads it as a shebang, ending at a line feed as
    // rustc's does. Where `#` is a comment it is one like any `#` line, read by the loop below.
    let is_rust = extension(name).as_deref() == Some("rs");
    if is_rust && rust_shebang(&s) {
        // rustc's shebang ends at a line feed alone.
        while i < s.len() && s[i] != '\n' {
            out.push(s[i]);
            i += 1;
        }
        out.push('\n');
    }
    // An XML declaration before an `<!-- -->` file's comments.
    if syn == Syntax::Angle {
        let mut j = 0;
        while j < s.len() && s[j].is_whitespace() {
            j += 1;
        }
        // The XML declaration alone — `<?xml` and then whitespace or `?` — not any processing instruction.
        if at(j, "<?xml") && s.get(j + 5).is_some_and(|c| c.is_whitespace() || *c == '?') {
            while j < s.len() && !at(j, "?>") {
                j += 1;
            }
            i = j + 2;
        }
    }
    loop {
        while i < s.len() && s[i].is_whitespace() {
            i += 1;
        }
        match syn {
            Syntax::Slash { nests } => {
                if at(i, "//") {
                    line(&mut i, &mut out);
                } else if at(i, "/*") {
                    i += 2;
                    let mut depth = 1usize;
                    while i < s.len() && depth > 0 {
                        // A nested block's delimiters leave the header's text, its own text staying.
                        if nests && at(i, "/*") {
                            depth += 1;
                            i += 2;
                        } else if at(i, "*/") {
                            depth -= 1;
                            i += 2;
                        } else {
                            out.push(s[i]);
                            i += 1;
                        }
                    }
                    out.push('\n');
                } else {
                    break;
                }
            }
            Syntax::Block if at(i, "/*") => {
                i += 2;
                while i < s.len() && !at(i, "*/") {
                    out.push(s[i]);
                    i += 1;
                }
                i += 2;
                out.push('\n');
            }
            Syntax::Hash if at(i, "#") => line(&mut i, &mut out),
            Syntax::Semicolon if at(i, ";") => line(&mut i, &mut out),
            Syntax::Dash if at(i, "--") => line(&mut i, &mut out),
            Syntax::Angle if at(i, "<!--") => {
                i += 4;
                while i < s.len() && !at(i, "-->") {
                    out.push(s[i]);
                    i += 1;
                }
                i += 3;
                out.push('\n');
            }
            _ => break,
        }
    }
    out
}

/// Whether the file at `path` is marked as generated: its header holds one of [`MARKERS`], in any case.
#[must_use]
pub fn marked(path: &str, bytes: &[u8]) -> bool {
    let h = header(path, bytes).to_lowercase();
    MARKERS.iter().any(|m| h.contains(m))
}

